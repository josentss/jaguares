CREATE TABLE IF NOT EXISTS public.temporadas_deportivas (
    id_temporada INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT temporadas_deportivas_nombre_valido
      CHECK (char_length(btrim(nombre)) BETWEEN 2 AND 80)
);
CREATE UNIQUE INDEX IF NOT EXISTS temporadas_deportivas_nombre_ci
    ON public.temporadas_deportivas (lower(btrim(nombre)));

CREATE TABLE IF NOT EXISTS public.categorias_deportivas (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_temporada INTEGER NOT NULL REFERENCES public.temporadas_deportivas(id_temporada) ON DELETE RESTRICT,
    nombre VARCHAR(80) NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT categorias_deportivas_nombre_valido
      CHECK (char_length(btrim(nombre)) BETWEEN 2 AND 80)
);
CREATE UNIQUE INDEX IF NOT EXISTS categorias_deportivas_nombre_ci
    ON public.categorias_deportivas (id_temporada, lower(btrim(nombre)));

CREATE TABLE IF NOT EXISTS public.equipos_deportivos (
    id_equipo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria INTEGER NOT NULL REFERENCES public.categorias_deportivas(id_categoria) ON DELETE RESTRICT,
    nombre VARCHAR(80) NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT equipos_deportivos_nombre_valido
      CHECK (char_length(btrim(nombre)) BETWEEN 2 AND 80)
);
CREATE UNIQUE INDEX IF NOT EXISTS equipos_deportivos_nombre_ci
    ON public.equipos_deportivos (id_categoria, lower(btrim(nombre)));

COMMIT;
