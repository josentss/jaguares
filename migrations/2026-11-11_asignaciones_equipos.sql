BEGIN;

CREATE TABLE IF NOT EXISTS asignaciones_equipos (
    id_asignacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_atleta INTEGER NOT NULL REFERENCES atletas(id_atleta) ON DELETE RESTRICT,
    id_equipo INTEGER NOT NULL REFERENCES equipos_deportivos(id_equipo) ON DELETE RESTRICT,
    id_temporada INTEGER NOT NULL REFERENCES temporadas_deportivas(id_temporada) ON DELETE RESTRICT,
    inicio_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    fin_en TIMESTAMPTZ,
    asignado_por INTEGER NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    cerrado_por INTEGER REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    CONSTRAINT asignaciones_equipos_fechas CHECK (fin_en IS NULL OR fin_en >= inicio_en),
    CONSTRAINT asignaciones_equipos_cierre CHECK ((fin_en IS NULL) = (cerrado_por IS NULL))
);

CREATE UNIQUE INDEX IF NOT EXISTS asignaciones_equipos_activa_unica
    ON asignaciones_equipos (id_atleta, id_temporada) WHERE fin_en IS NULL;
CREATE INDEX IF NOT EXISTS asignaciones_equipos_equipo_activo
    ON asignaciones_equipos (id_equipo) WHERE fin_en IS NULL;
CREATE INDEX IF NOT EXISTS asignaciones_equipos_atleta_historial
    ON asignaciones_equipos (id_atleta, inicio_en DESC);

COMMIT;
