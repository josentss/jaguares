-- Ampliación manual y aditiva: conceptos editables, nuevos cargos y tasas trazables.
-- NO ejecutada por deploy. Respaldar Supabase y comprobar el esquema ANTES.
-- Conserva pagos históricos, anclas, obligaciones y tarifas ya emitidas.
BEGIN;

-- El catálogo original limita los códigos a cinco: retirar solo esa restricción,
-- manteniendo esos cinco como conceptos institucionales reservados.
ALTER TABLE conceptos_cobro
    DROP CONSTRAINT IF EXISTS conceptos_cobro_codigo_check;
ALTER TABLE conceptos_cobro
    DROP CONSTRAINT IF EXISTS conceptos_cobro_modalidad;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
        WHERE conrelid = 'conceptos_cobro'::regclass
          AND conname = 'conceptos_cobro_codigo_formato') THEN
        ALTER TABLE conceptos_cobro
            ADD CONSTRAINT conceptos_cobro_codigo_formato
            CHECK (codigo ~ '^[a-z][a-z0-9_]{2,39}$');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
        WHERE conrelid = 'conceptos_cobro'::regclass
          AND conname = 'conceptos_cobro_modalidad_segura') THEN
        ALTER TABLE conceptos_cobro
            ADD CONSTRAINT conceptos_cobro_modalidad_segura
            CHECK (
                (codigo = 'inscripcion' AND modalidad = 'unica')
                OR (codigo = 'mensualidad' AND modalidad = 'mensual')
                OR (codigo NOT IN ('inscripcion', 'mensualidad') AND modalidad = 'manual')
            );
    END IF;
END $$;

-- Las tasas no se calculan automáticamente a partir del dashboard ni de un
-- fallback ficticio; las registra la Directiva con fuente y fecha explícitas.
-- Puede haber correcciones en el mismo día; la última se aplica a FUTUROS
-- reportes, mientras cada pago conserva el ID de su tasa original.
CREATE TABLE IF NOT EXISTS tasas_cobro (
    id_tasa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moneda TEXT NOT NULL CHECK (moneda IN ('Bs', 'COP')),
    fecha_vigencia DATE NOT NULL,
    tasa_por_usd NUMERIC(18,6) NOT NULL
        CHECK (tasa_por_usd > 0 AND tasa_por_usd <= 999999999),
    fuente VARCHAR(120) NOT NULL
        CHECK (char_length(btrim(fuente)) BETWEEN 3 AND 120),
    creado_por INTEGER NOT NULL REFERENCES usuarios(id_usuario)
        ON DELETE RESTRICT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS tasas_cobro_vigencia
    ON tasas_cobro (moneda, fecha_vigencia, id_tasa DESC);

ALTER TABLE pagos ADD COLUMN IF NOT EXISTS id_tasa_cobro BIGINT;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
        WHERE conrelid = 'pagos'::regclass
          AND conname = 'pagos_tasa_cobro_fk') THEN
        ALTER TABLE pagos
            ADD CONSTRAINT pagos_tasa_cobro_fk
            FOREIGN KEY (id_tasa_cobro)
            REFERENCES tasas_cobro(id_tasa)
            ON DELETE RESTRICT;
    END IF;
END $$;

-- Tasas usadas son inmutables: para cambiar una cifra se inserta otra fila.
CREATE OR REPLACE FUNCTION proteger_tasas_cobro()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Las tasas de cobro son inmutables; registra una tasa nueva';
END $$;
DROP TRIGGER IF EXISTS tasas_cobro_inmutables ON tasas_cobro;
CREATE TRIGGER tasas_cobro_inmutables
    BEFORE UPDATE OR DELETE ON tasas_cobro
    FOR EACH ROW EXECUTE FUNCTION proteger_tasas_cobro();

-- Impedir dos cargos manuales iguales al mismo atleta/concepto/día/detalle.
-- Los índices preexistentes de inscripción única y mensualidad única permanecen.
CREATE UNIQUE INDEX IF NOT EXISTS obligaciones_cobro_manual_identidad
    ON obligaciones_cobro
        (id_atleta, codigo_concepto, fecha_vencimiento,
         COALESCE(detalle, ''))
    WHERE codigo_concepto NOT IN ('inscripcion', 'mensualidad');

COMMIT;
