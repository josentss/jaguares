-- Base de cuentas por cobrar: migracion ADITIVA, MANUAL y sin backfill.
-- No ejecutar desde la aplicacion. Requiere respaldo, preflight y autorizacion.
-- No altera importes/estados de pagos antiguos ni genera deudas automaticamente.
BEGIN;

CREATE TABLE IF NOT EXISTS conceptos_cobro (
    codigo TEXT PRIMARY KEY
        CHECK (codigo IN ('inscripcion', 'mensualidad', 'torneo', 'arbitraje', 'sancion')),
    nombre VARCHAR(60) NOT NULL CHECK (char_length(btrim(nombre)) BETWEEN 2 AND 60),
    modalidad TEXT NOT NULL CHECK (modalidad IN ('unica', 'mensual', 'manual')),
    monto_referencia_usd NUMERIC(12,2) NOT NULL CHECK (monto_referencia_usd > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT conceptos_cobro_modalidad CHECK (
        (codigo = 'inscripcion' AND modalidad = 'unica')
        OR (codigo = 'mensualidad' AND modalidad = 'mensual')
        OR (codigo IN ('torneo', 'arbitraje', 'sancion') AND modalidad = 'manual')
    )
);

-- Los importes de los conceptos manuales son REFERENCIAS, no deudas automaticas.
-- ON CONFLICT no modifica tarifas configuradas si se revisa esta migracion.
INSERT INTO conceptos_cobro (codigo, nombre, modalidad, monto_referencia_usd) VALUES
    ('inscripcion', 'Inscripción', 'unica', 15.00),
    ('mensualidad', 'Mensualidad', 'mensual', 15.00),
    ('torneo', 'Torneo', 'manual', 40.00),
    ('arbitraje', 'Arbitraje por juego', 'manual', 9.00),
    ('sancion', 'Sanción', 'manual', 10.00)
ON CONFLICT (codigo) DO NOTHING;

-- Vacio inicialmente: no inferir fechas ni cobros de los registros historicos.
CREATE TABLE IF NOT EXISTS anclas_cobro_atleta (
    id_atleta INTEGER PRIMARY KEY REFERENCES atletas(id_atleta) ON DELETE RESTRICT,
    fecha_inicio DATE NOT NULL,
    dia_ancla SMALLINT NOT NULL CHECK (dia_ancla BETWEEN 1 AND 31),
    configurado_por INTEGER REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    configurado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- El estado financiero se deriva de los reportes asociados y su revision:
-- sin reporte -> pendiente; reporte pendiente -> en revision;
-- reporte aprobado -> pagada; reporte rechazado -> pendiente nuevamente.
CREATE TABLE IF NOT EXISTS obligaciones_cobro (
    id_obligacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_atleta INTEGER NOT NULL REFERENCES atletas(id_atleta) ON DELETE RESTRICT,
    codigo_concepto TEXT NOT NULL REFERENCES conceptos_cobro(codigo) ON DELETE RESTRICT,
    periodo_mes DATE,
    detalle VARCHAR(160),
    monto_usd NUMERIC(12,2) NOT NULL CHECK (monto_usd > 0),
    fecha_emision DATE NOT NULL,
    fecha_vencimiento DATE NOT NULL,
    fecha_limite DATE NOT NULL,
    origen TEXT NOT NULL CHECK (origen IN ('sistema', 'directiva')),
    creado_por INTEGER REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT obligaciones_cobro_fechas CHECK (fecha_limite >= fecha_vencimiento),
    CONSTRAINT obligaciones_cobro_periodo CHECK (
        (codigo_concepto = 'mensualidad'
            AND periodo_mes IS NOT NULL
            AND EXTRACT(DAY FROM periodo_mes) = 1
            AND date_trunc('month', fecha_vencimiento)::date = periodo_mes
            AND fecha_limite = (date_trunc('month', fecha_vencimiento)
                + INTERVAL '1 month - 1 day')::date)
        OR (codigo_concepto <> 'mensualidad' AND periodo_mes IS NULL)
    ),
    CONSTRAINT obligaciones_cobro_variables_manuales CHECK (
        codigo_concepto IN ('inscripcion', 'mensualidad') OR origen = 'directiva'
    ),
    CONSTRAINT obligaciones_cobro_id_y_atleta UNIQUE (id_obligacion, id_atleta)
);

CREATE UNIQUE INDEX IF NOT EXISTS obligaciones_cobro_inscripcion_unica
    ON obligaciones_cobro (id_atleta) WHERE codigo_concepto = 'inscripcion';
CREATE UNIQUE INDEX IF NOT EXISTS obligaciones_cobro_mensualidad_unica
    ON obligaciones_cobro (id_atleta, periodo_mes) WHERE codigo_concepto = 'mensualidad';
CREATE INDEX IF NOT EXISTS obligaciones_cobro_consulta_atleta
    ON obligaciones_cobro (id_atleta, fecha_vencimiento, id_obligacion);

-- Nullable: los pagos existentes se mantienen INTACTOS y no se vinculan
-- por nombre de mes, que hoy no contiene anio.
ALTER TABLE pagos ADD COLUMN IF NOT EXISTS id_obligacion BIGINT;

-- La asociacion solo puede hacerse con una obligacion DEL MISMO atleta.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'pagos'::regclass
          AND conname = 'pagos_obligacion_atleta_fk'
    ) THEN
        ALTER TABLE pagos
            ADD CONSTRAINT pagos_obligacion_atleta_fk
            FOREIGN KEY (id_obligacion, id_atleta)
            REFERENCES obligaciones_cobro(id_obligacion, id_atleta)
            ON DELETE RESTRICT;
    END IF;
END $$;

-- Permite historicos/rechazados sin impedir la correccion del representante.
-- Impide dos reportes simultaneos pendientes/aprobados para una misma deuda.
CREATE UNIQUE INDEX IF NOT EXISTS pagos_obligacion_un_reporte_activo
    ON pagos (id_obligacion)
    WHERE id_obligacion IS NOT NULL AND estado_pago IN ('pendiente', 'aprobado');

COMMIT;
