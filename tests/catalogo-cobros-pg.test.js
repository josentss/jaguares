async function invocar(fn,req={}) {
    let resolver;
    const promesa=new Promise(resolve=>{resolver=resolve;});
    const res={
        codigo:200,
        status(n){this.codigo=n;return this;},
        set(){return this;},
        json(body){resolver({codigo:this.codigo,body});return this;}
    };
    await fn(req,res);
    return promesa;
}

test.before(async()=>{
    await db.pool.query(`CREATE SCHEMA ${schema}`);
    existe=true;
    await db.pool.query(`
        CREATE TABLE usuarios(id_usuario INT PRIMARY KEY,rol TEXT,estado TEXT);
        CREATE TABLE atletas(
            id_atleta INT PRIMARY KEY,id_representante INT REFERENCES usuarios(id_usuario),
            estado TEXT
        );
        CREATE TABLE pagos(
            id_pago INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            id_atleta INT REFERENCES atletas(id_atleta),mes_pagado TEXT,estado_pago TEXT,
            moneda TEXT,monto NUMERIC(12,2)
        );
        INSERT INTO usuarios VALUES (9,'directiva','aprobado'),(5,'representante','aprobado'),
            (6,'representante','aprobado');
        INSERT INTO atletas VALUES (11,5,'activo'),(12,6,'activo');
        INSERT INTO pagos(id_atleta,mes_pagado,estado_pago,moneda,monto)
            VALUES (11,'Noviembre','aprobado','Bs',10000.00);
    `);
    for(const m of migrations) {
        await db.pool.query(fs.readFileSync(path.join(__dirname,'../migrations',m),'utf8'));
    }
});
test.after(async()=>{
    try{if(existe)await db.pool.query(`DROP SCHEMA ${schema} CASCADE`);}
    finally{await db.pool.end();}
});

test('la migración es repetible; el histórico y catálogo original permanecen',async()=>{
    await db.pool.query(fs.readFileSync(path.join(__dirname,
        '../migrations/2026-11-12_catalogo_y_tasas_cobro.sql'),'utf8'));
    const {rows}=await db.pool.query('SELECT codigo FROM conceptos_cobro ORDER BY codigo');
    assert.equal(rows.length,5);
    const {rows:pagos}=await db.pool.query('SELECT id_obligacion,id_tasa_cobro,monto FROM pagos');
    assert.equal(pagos.length,1);
    assert.equal(pagos[0].id_obligacion,null);
    assert.equal(pagos[0].id_tasa_cobro,null);
    assert.equal(pagos[0].monto,'10000.00');
});

