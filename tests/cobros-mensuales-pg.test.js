const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const { configurarPostgresTemporal } = require('./helpers/postgres');
const esquema = configurarPostgresTemporal();
const db = require('../config/db');
const cobros = require('../controllers/cobrosController');
const { hoyCaracas, periodoDe, siguientePeriodo } = require('../utils/cobrosMensuales');
const migracion = fs.readFileSync(path.join(__dirname,
    '../migrations/2026-11-12_cuentas_por_cobrar_base.sql'), 'utf8');
let creado = false;

async function invocar(fn, req) {
    let finalizar;
    const fin = new Promise(resolve => { finalizar = resolve; });
    const res = {
        codigo: 200,
        status(n) { this.codigo = n; return this; },
        set() { return this; },
        json(body) { finalizar({ codigo: this.codigo, body }); return this; }
    };
    await fn(req, res);
    return fin;
}
const admin = { usuarioId: 9, usuarioRol: 'directiva' };
const rep = { usuarioId: 5, usuarioRol: 'representante' };
const actual = periodoDe(hoyCaracas());
const proximo = siguientePeriodo(actual);

test.before(async () => {
    await db.pool.query(`CREATE SCHEMA ${esquema}`);
    creado = true;
    await db.pool.query(`
        CREATE TABLE usuarios (
            id_usuario INTEGER PRIMARY KEY, rol TEXT NOT NULL, estado TEXT NOT NULL
        );
        CREATE TABLE atletas (
            id_atleta INTEGER PRIMARY KEY,
            id_representante INTEGER NOT NULL REFERENCES usuarios(id_usuario),
            estado TEXT NOT NULL
        );
        CREATE TABLE pagos (
            id_pago INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            id_atleta INTEGER NOT NULL REFERENCES atletas(id_atleta),
            mes_pagado TEXT, monto NUMERIC(12,2),
            estado_pago TEXT CHECK (estado_pago IN ('pendiente','aprobado','rechazado'))
        );
        INSERT INTO usuarios VALUES (5, 'representante', 'aprobado'),
            (6, 'representante', 'aprobado'), (9, 'directiva', 'aprobado');
        INSERT INTO atletas VALUES (11,5,'activo'), (12,5,'inactivo'),
            (13,6,'activo'), (14,5,'activo');
        INSERT INTO pagos (id_atleta, mes_pagado, monto, estado_pago)
            VALUES (11,'Octubre',15,'aprobado'), (11,'Septiembre',15,'rechazado');
    `);
    await db.pool.query(migracion);
});

test.after(async () => {
    try { if (creado) await db.pool.query(`DROP SCHEMA ${esquema} CASCADE`); }
    finally { await db.pool.end(); }
});

test('lectura de representante propio, ajeno 403 y sin obligaciones iniciales', async () => {
    const propio = await invocar(cobros.consultar, { ...rep, params: { id_atleta: 11 } });
    assert.equal(propio.codigo, 200);
    assert.deepEqual(propio.body.obligaciones, []);
    assert.equal(propio.body.ancla, null);
    const ajeno = await invocar(cobros.consultar, {
        ...rep, usuarioId: 6, params: { id_atleta: 11 }
    });
    assert.equal(ajeno.codigo, 403);
    const invalido = await invocar(cobros.consultar, { ...rep, params: { id_atleta: 'xyz' } });
    assert.equal(invalido.codigo, 400);
});

test('alta de ancla exige confirmación de historial y rol privilegiado', async () => {
    const body = { fecha_inicio: actual, dia_ancla: 15, historial_revisado: true };
    const req = { ...admin, params: { id_atleta: 11 }, body };
    assert.equal((await invocar(cobros.configurarAncla, { ...req, usuarioRol: 'staff' })).codigo, 403);
    assert.equal((await invocar(cobros.configurarAncla, {
        ...req, body: { ...body, historial_revisado: false }
    })).codigo, 400);
    assert.equal((await invocar(cobros.configurarAncla, req)).codigo, 201);
    assert.equal((await invocar(cobros.configurarAncla, req)).codigo, 409);
    assert.equal((await invocar(cobros.configurarAncla, {
        ...req, params: { id_atleta: 12 }
    })).codigo, 409);
    const { rows } = await db.pool.query('SELECT fecha_inicio, dia_ancla, configurado_por FROM anclas_cobro_atleta WHERE id_atleta = 11');
    assert.equal(rows[0].fecha_inicio, actual);
    assert.equal(rows[0].dia_ancla, 15);
    assert.equal(rows[0].configurado_por, 9);
});

test('genera solo mes actual/siguiente con confirmación y nunca dos veces', async () => {
    const body = { id_atleta: 11, periodo_mes: actual, confirmar: true };
    assert.equal((await invocar(cobros.generarMensualidad, { ...admin, body: { ...body, confirmar: false } })).codigo, 400);
    assert.equal((await invocar(cobros.generarMensualidad, { ...admin, usuarioRol: 'staff', body })).codigo, 403);
    assert.equal((await invocar(cobros.generarMensualidad, { ...admin, body: { ...body, id_atleta: 13 } })).codigo, 409);
    assert.equal((await invocar(cobros.generarMensualidad, {
        ...admin, body: { ...body, periodo_mes: siguientePeriodo(proximo) }
    })).codigo, 409);

    const primero = await invocar(cobros.generarMensualidad, { ...admin, body });
    assert.equal(primero.codigo, 201);
    assert.equal(primero.body.creada, true);
    assert.equal(primero.body.obligacion.monto_usd, '15.00');
    const segundo = await invocar(cobros.generarMensualidad, { ...admin, body });
    assert.equal(segundo.codigo, 200);
    assert.equal(segundo.body.creada, false);
    assert.equal(segundo.body.obligacion.id_obligacion, primero.body.obligacion.id_obligacion);
    const { rows } = await db.pool.query('SELECT count(*)::int AS total FROM obligaciones_cobro');
    assert.equal(rows[0].total, 1);
});

test('cambio de tarifa afecta solo nuevas deudas; el histórico permanece intacto', async () => {
    await db.pool.query("UPDATE conceptos_cobro SET monto_referencia_usd=20 WHERE codigo='mensualidad'");
    const nueva = await invocar(cobros.generarMensualidad, {
        ...admin, body: { id_atleta: 11, periodo_mes: proximo, confirmar: true }
    });
    assert.equal(nueva.codigo, 201);
    assert.equal(nueva.body.obligacion.monto_usd, '20.00');
    const { rows: deudas } = await db.pool.query(
        'SELECT periodo_mes, monto_usd FROM obligaciones_cobro ORDER BY periodo_mes');
    assert.deepEqual(deudas.map(o => o.monto_usd), ['15.00','20.00']);
    const { rows: antiguos } = await db.pool.query(
        'SELECT mes_pagado, monto, id_obligacion FROM pagos ORDER BY id_pago');
    assert.equal(antiguos.length, 2);
    assert.ok(antiguos.every(p => p.id_obligacion === null));
    assert.equal(antiguos[0].monto, '15.00');
});

test('la lectura muestra obligaciones propias, importes y evita exponer ajenas', async () => {
    const propio = await invocar(cobros.consultar, { ...rep, params: { id_atleta: 11 } });
    assert.equal(propio.codigo, 200);
    assert.equal(propio.body.obligaciones.length, 2);
    assert.equal(propio.body.ancla.dia_ancla, 15);
    assert.equal(propio.body.obligaciones[0].periodo_mes, actual);
    assert.equal(propio.body.obligaciones[1].periodo_mes, proximo);
    assert.equal(Object.hasOwn(propio.body.obligaciones[0], 'existe_aprobado'), false);
    assert.equal((await invocar(cobros.consultar, { ...rep, usuarioId: 6,
        params: { id_atleta: 11 } })).codigo, 403);
    assert.equal((await invocar(cobros.consultar, { ...admin, params: { id_atleta: 11 } })).codigo, 200);
});

test('dos altas concurrentes de la misma mensualidad no duplican obligación', async () => {
    const body = { id_atleta: 11, periodo_mes: actual, confirmar: true };
    const [a,b] = await Promise.all([
        invocar(cobros.generarMensualidad, { ...admin, body }),
        invocar(cobros.generarMensualidad, { ...admin, body })
    ]);
    assert.equal(a.codigo, 200);
    assert.equal(b.codigo, 200);
    const { rows } = await db.pool.query(
        "SELECT count(*)::int AS total FROM obligaciones_cobro WHERE id_atleta=11 AND codigo_concepto='mensualidad'");
    assert.equal(rows[0].total, 2);
});
