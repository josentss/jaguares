'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { configurarPostgresTemporal } = require('./helpers/postgres');
const esquema = configurarPostgresTemporal();
const db = require('../config/db');
const conciliacion = require('../controllers/cobrosConciliacionController');
const migracion = fs.readFileSync(path.join(__dirname,
    '../migrations/2026-11-12_cuentas_por_cobrar_base.sql'), 'utf8');
let creada = false;

async function llamar(fn, req) {
    let fin;
    const promesa = new Promise(resolve => { fin = resolve; });
    const res = {
        codigo: 200,
        set() { return this; },
        status(n) { this.codigo = n; return this; },
        json(body) { fin({ codigo: this.codigo, body }); return this; }
    };
    await fn(req, res);
    return promesa;
}
const directiva = { usuarioRol: 'directiva', usuarioId: 9 };

test.before(async () => {
    await db.pool.query(`CREATE SCHEMA ${esquema}`);
    creada = true;
    await db.pool.query(`
        CREATE TABLE usuarios (
            id_usuario INTEGER PRIMARY KEY, rol TEXT NOT NULL,
            estado TEXT NOT NULL
        );
        CREATE TABLE atletas (
            id_atleta INTEGER PRIMARY KEY,
            id_representante INTEGER REFERENCES usuarios(id_usuario),
            nombres TEXT, apellidos TEXT, estado TEXT
        );
        CREATE TABLE pagos (
            id_pago INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            id_atleta INTEGER NOT NULL REFERENCES atletas(id_atleta),
            mes_pagado TEXT, fecha_pago DATE, monto NUMERIC(12,2),
            moneda TEXT, estado_pago TEXT, metodo_pago TEXT
        );
        INSERT INTO usuarios VALUES
            (9,'directiva','aprobado'),(5,'representante','aprobado');
        INSERT INTO atletas VALUES
            (31,5,'Atleta','Activo','activo'),
            (32,5,'Atleta','Inactivo','inactivo');
        INSERT INTO pagos
            (id_atleta,mes_pagado,fecha_pago,monto,moneda,estado_pago,metodo_pago)
            VALUES
            (31,'Noviembre','2026-11-08',15,'USD','aprobado','Efectivo'),
            (31,'Octubre','2026-10-08',15,'USD','pendiente','Efectivo'),
            (31,'Septiembre','2026-09-08',15,'USD','rechazado','Efectivo');
    `);
    await db.pool.query(migracion);
});

test.after(async () => {
    try { if (creada) await db.pool.query(`DROP SCHEMA ${esquema} CASCADE`); }
    finally { await db.pool.end(); }
});

test('solo Directiva/Admin consultan conciliación, representantes y staff reciben 403', async () => {
    for (const usuarioRol of ['representante','staff']) {
        assert.equal((await llamar(conciliacion.listarAtletas, { usuarioRol })).codigo, 403);
        assert.equal((await llamar(conciliacion.verDetalle, {
            usuarioRol, params: { id_atleta: '31' }
        })).codigo, 403);
    }
    assert.equal((await llamar(conciliacion.listarAtletas, {
        usuarioRol:'admin'
    })).codigo, 200);
});

test('lista muestra datos mínimos, ancla y conteos de cada estado', async () => {
    const respuesta = await llamar(conciliacion.listarAtletas, directiva);
    assert.equal(respuesta.codigo, 200);
    assert.equal(respuesta.body.atletas.length, 2);
    const atleta = respuesta.body.atletas.find(a => a.id_atleta === 31);
    assert.equal(atleta.total_pagos, 3);
    assert.equal(atleta.aprobados, 1);
    assert.equal(atleta.pendientes, 1);
    assert.equal(atleta.rechazados, 1);
    assert.equal(atleta.fecha_inicio, null);
});

test('detalle conserva meses sin inventar año o vincular pagos a deudas', async () => {
    const respuesta = await llamar(conciliacion.verDetalle, {
        ...directiva, params: { id_atleta:'31' }
    });
    assert.equal(respuesta.codigo, 200);
    assert.equal(respuesta.body.pagos.length, 3);
    assert.equal(respuesta.body.pagos[0].mes_pagado, 'Noviembre');
    assert.equal(respuesta.body.historial_sin_periodo_anual, true);
    assert.equal(respuesta.body.obligaciones.length, 0);
    assert.ok(respuesta.body.pagos.every(p => p.id_obligacion === null));
    assert.equal(Object.hasOwn(respuesta.body.pagos[0], 'ruta_captura'),false);
    assert.equal(Object.hasOwn(respuesta.body.pagos[0], 'referencia'),false);
});

test('ID inválido retorna 400 e inexistente 404 sin modificaciones', async () => {
    assert.equal((await llamar(conciliacion.verDetalle, {
        ...directiva, params:{id_atleta:'abc'}
    })).codigo,400);
    assert.equal((await llamar(conciliacion.verDetalle, {
        ...directiva, params:{id_atleta:'999'}
    })).codigo,404);
    const { rows } = await db.pool.query(
        'SELECT count(*)::int AS anclas FROM anclas_cobro_atleta'
    );
    assert.equal(rows[0].anclas,0);
    const { rows: pagos } = await db.pool.query(
        'SELECT count(*)::int AS total FROM pagos WHERE id_obligacion IS NOT NULL'
    );
    assert.equal(pagos[0].total,0);
});
