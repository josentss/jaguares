test('no crear una tasa automática si el importe del reporte es incorrecto',async()=>{
    const r=await enviar(11,ids.a,'10000.00');
    assert.equal(r.codigo,409);
    assert.equal((await db.pool.query('SELECT * FROM tasas_cobro')).rowCount,0);
    assert.equal((await db.pool.query('SELECT * FROM pagos')).rowCount,0);
});

test('dos pagos simultáneos guardan una sola tasa automática y cada pago la referencia',async()=>{
    const [a,b]=await Promise.all([
        enviar(11,ids.a,'13674.36'),
        enviar(12,ids.b,'13674.36',hoy,repB)
    ]);
    assert.equal(a.codigo,200,JSON.stringify(a.body));
    assert.equal(b.codigo,200,JSON.stringify(b.body));
    const tasas=await db.pool.query('SELECT id_tasa,tasa_por_usd,fuente,creado_por FROM tasas_cobro');
    assert.equal(tasas.rowCount,1);
    assert.equal(tasas.rows[0].tasa_por_usd,'911.624300');
    assert.match(tasas.rows[0].fuente,/ExchangeRate-API/);
    assert.ok([5,6].includes(Number(tasas.rows[0].creado_por)));
    const pagosDB=await db.pool.query(
        'SELECT id_tasa_cobro,monto FROM pagos ORDER BY id_pago');
    assert.equal(pagosDB.rowCount,2);
    assert.ok(pagosDB.rows.every(p=>p.id_tasa_cobro===tasas.rows[0].id_tasa));
    assert.ok(pagosDB.rows.every(p=>p.monto==='13674.36'));
    assert.equal(solicitudesExteriores,0);
    assert.equal((await enviar(11,ids.a,'13674.36')).codigo,409);
});

test('Directiva mantiene prioridad si publica otra tasa para el mismo día',async()=>{
    const creada=await db.pool.query(`
        INSERT INTO tasas_cobro(moneda,fecha_vigencia,tasa_por_usd,fuente,creado_por)
        VALUES ('Bs',$1,900.000000,'Directiva confirmación manual',9)
        RETURNING id_tasa
    `,[hoy]);
    const c=await consulta(ids.c);
    assert.equal(c.codigo,200);
    assert.equal(c.body.monto,'36000.00');
    assert.match(c.body.fuente,/Directiva/);
    const reporte=await enviar(11,ids.c,'36000.00');
    assert.equal(reporte.codigo,200);
    const {rows}=await db.pool.query(
        'SELECT id_tasa_cobro FROM pagos WHERE id_obligacion=$1',[ids.c]);
    assert.equal(rows[0].id_tasa_cobro,creada.rows[0].id_tasa);
    // El pago anterior sigue asociado al tipo de cambio histórico original.
    const historico=await db.pool.query(
        'SELECT tasa_por_usd FROM tasas_cobro WHERE id_tasa=(SELECT id_tasa_cobro FROM pagos WHERE id_obligacion=$1)',
        [ids.a]);
    assert.equal(historico.rows[0].tasa_por_usd,'911.624300');
});

