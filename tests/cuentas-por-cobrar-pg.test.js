const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { configurarPostgresTemporal } = require('./helpers/postgres');

const schema = configurarPostgresTemporal();
const db = require('../config/db');
const sql = fs.readFileSync(path.join(__dirname, '../migrations/2026-11-12_cuentas_por_cobrar_base.sql'), 'utf8');
let creado = false;

test.before(async () => {
    await db.pool.query(`CREATE SCHEMA ${schema}`);
    creado = true;
    await db.pool.query(`
        CREATE TABLE usuarios (id_usuario INTEGER PRIMARY KEY);
        CREATE TABLE atletas (
            id_atleta INTEGER PRIMARY KEY,
            id_representante INTEGER REFERENCES usuarios(id_usuario)
        );
        CREATE TABLE pagos (
            id_pago INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            id_atleta INTEGER NOT NULL REFERENCES atletas(id_atleta),
            mes_pagado TEXT,
            monto NUMERIC(12,2),
            estado_pago TEXT CHECK (estado_pago IN ('pendiente','aprobado','rechazado'))
        );
        INSERT INTO usuarios VALUES (1);
        INSERT INTO atletas VALUES (11, 1), (12, 1);
        INSERT INTO pagos (id_atleta, mes_pagado, monto, estado_pago)
            VALUES (11, 'Octubre', 15.00, 'aprobado');
    `);
});

test.after(async () => {
    try {
        if (creado) await db.pool.query(`DROP SCHEMA ${schema} CASCADE`);
    } finally { await db.pool.end(); }
});

test('Migracion aditiva e idempotente conserva pagos historicos', async () => {
    await db.pool.query(sql);
    await db.pool.query(sql);
    const {rows: pagos} = await db.pool.query(
        'SELECT id_atleta, mes_pagado, monto, estado_pago, id_obligacion FROM pagos');
    assert.equal(pagos.length, 1);
    assert.equal(pagos[0].id_obligacion, null);
    assert.equal(pagos[0].mes_pagado, 'Octubre');
    assert.equal(pagos[0].monto, '15.00');
    assert.equal(pagos[0].estado_pago, 'aprobado');
    const {rows: oblig} = await db.pool.query('SELECT count(*)::int AS total FROM obligaciones_cobro');
    assert.equal(oblig[0].total, 0);
    const {rows: conceptos} = await db.pool.query('SELECT codigo FROM conceptos_cobro ORDER BY codigo');
    assert.deepEqual(conceptos.map(c => c.codigo), ['arbitraje','inscripcion','mensualidad','sancion','torneo']);
});

test('Unicidad por atleta, mes e inscripcion y precios historicos congelados', async () => {
    await db.pool.query(`
        INSERT INTO anclas_cobro_atleta(id_atleta,fecha_inicio,dia_ancla)
            VALUES (11,'2026-10-15',15);
        INSERT INTO obligaciones_cobro
        (id_atleta,codigo_concepto,periodo_mes,monto_usd,fecha_emision,fecha_vencimiento,fecha_limite,origen)
        VALUES (11,'mensualidad','2026-11-01',15,'2026-11-01','2026-11-15','2026-11-30','sistema');
    `);
    const insertarDuplicado = `INSERT INTO obligaciones_cobro
        (id_atleta,codigo_concepto,periodo_mes,monto_usd,fecha_emision,fecha_vencimiento,fecha_limite,origen)
        VALUES (11,'mensualidad','2026-11-01',15,'2026-11-01','2026-11-15','2026-11-30','sistema')`;
    await assert.rejects(db.pool.query(insertarDuplicado), e => e.code === '23505');
    await assert.rejects(db.pool.query(insertarDuplicado.replace('2026-11-30', '2026-12-01')),
        e => e.code === '23514');
    await db.pool.query(`INSERT INTO obligaciones_cobro
        (id_atleta,codigo_concepto,monto_usd,fecha_emision,fecha_vencimiento,fecha_limite,origen)
        VALUES (11,'inscripcion',15,'2026-10-15','2026-10-15','2026-10-31','sistema')`);
    await assert.rejects(db.pool.query(`INSERT INTO obligaciones_cobro
        (id_atleta,codigo_concepto,monto_usd,fecha_emision,fecha_vencimiento,fecha_limite,origen)
        VALUES (11,'inscripcion',15,'2027-10-15','2027-10-15','2027-10-31','sistema')`), e => e.code === '23505');
    await db.pool.query("UPDATE conceptos_cobro SET monto_referencia_usd = 20 WHERE codigo = 'mensualidad'");
    const {rows} = await db.pool.query(
        "SELECT monto_usd FROM obligaciones_cobro WHERE codigo_concepto = 'mensualidad'");
    assert.equal(rows[0].monto_usd, '15.00');
});

test('FK por atleta e indice de reporte activo impiden errores y duplicados', async () => {
    const {rows} = await db.pool.query(
        "SELECT id_obligacion FROM obligaciones_cobro WHERE codigo_concepto = 'mensualidad' AND id_atleta=11");
    const id = rows[0].id_obligacion;
    await assert.rejects(db.pool.query(
        "INSERT INTO pagos(id_atleta,id_obligacion,estado_pago) VALUES (12,$1,'pendiente')", [id]),
    e => e.code === '23503');
    await db.pool.query(
        "INSERT INTO pagos(id_atleta,id_obligacion,estado_pago) VALUES (11,$1,'rechazado')", [id]);
    await db.pool.query(
        "INSERT INTO pagos(id_atleta,id_obligacion,estado_pago) VALUES (11,$1,'pendiente')", [id]);
    await assert.rejects(db.pool.query(
        "INSERT INTO pagos(id_atleta,id_obligacion,estado_pago) VALUES (11,$1,'pendiente')", [id]),
    e => e.code === '23505');
    await assert.rejects(db.pool.query(
        "INSERT INTO pagos(id_atleta,id_obligacion,estado_pago) VALUES (11,$1,'aprobado')", [id]),
    e => e.code === '23505');
});
