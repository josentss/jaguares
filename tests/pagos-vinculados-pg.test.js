test.after(async () => {
    try { if (creada) await db.pool.query(`DROP SCHEMA ${esquema} CASCADE`); }
    finally { await db.pool.end(); }
});

test('legacy: no se aplica a atletas con ancla y conserva alta para los demás', async () => {
    const body = {id_atleta:'11',mes:'Noviembre',metodo:'Efectivo',
        monto:'15',moneda:'USD',fecha_pago:hoy};
    const bloqueado = await invocar(pagos.reportarPago,{...reps,body});
    assert.equal(bloqueado.codigo,409);
    const heredado = await invocar(pagos.reportarPago,{
        ...reps,body:{...body,id_atleta:'14'}
    });
    assert.equal(heredado.codigo,200);
    const {rows} = await db.pool.query(
        'SELECT id_obligacion,mes_pagado FROM pagos WHERE id_atleta=14');
    assert.equal(rows.length,1);
    assert.equal(rows[0].id_obligacion,null);
    assert.equal(rows[0].mes_pagado,'Noviembre');
});

test('reportes de atleta ajeno o inactivo y monto USD incorrecto se rechazan', async () => {
    const ajeno = await invocar(pagos.reportarPago,
        reporte(13,ids.ajeno,'15','USD'));
    assert.equal(ajeno.codigo,403);
    const inactivo = await invocar(pagos.reportarPago,
        reporte(12,ids.inactivo,'15','USD'));
    assert.equal(inactivo.codigo,409);
    const err = await invocar(pagos.reportarPago,
        reporte(11,ids.actual,'14.99','USD'));
    assert.equal(err.codigo,409);
    const futuro = await invocar(pagos.reportarPago,
        reporte(11,ids.actual,'15','USD',{fecha_pago:'2099-01-01'}));
    assert.equal(futuro.codigo,400);
    const { rows } = await db.pool.query(
        'SELECT count(*)::int AS total FROM pagos WHERE id_obligacion IS NOT NULL');
    assert.equal(rows[0].total,0);
});

test('USD exacto queda pendiente con id_obligacion y bloquea segundo reporte', async () => {
    const primero = await invocar(pagos.reportarPago,reporte(11,ids.actual));
    assert.equal(primero.codigo,200);
    assert.equal(primero.body.success,true);
    assert.equal(primero.body.id_obligacion,Number(ids.actual));
    const otro = await invocar(pagos.reportarPago,reporte(11,ids.actual));
    assert.equal(otro.codigo,409);
    const {rows}=await db.pool.query(
        'SELECT count(*)::int AS total FROM pagos WHERE id_obligacion=$1', [ids.actual]);
    assert.equal(rows[0].total,1);
});

test('concurrencia: un solo reporte activo de mismo cargo', async () => {
    const [a,b] = await Promise.all([
        invocar(pagos.reportarPago,reporte(11,ids.siguiente)),
        invocar(pagos.reportarPago,reporte(11,ids.siguiente))
    ]);
    assert.deepEqual([a.codigo,b.codigo].sort(),[200,409]);
    const {rows}=await db.pool.query(
        "SELECT count(*)::int AS total FROM pagos WHERE id_obligacion=$1 AND estado_pago='pendiente'",
        [ids.siguiente]);
    assert.equal(rows[0].total,1);
});

test('Directiva aprueba una vez USD y se bloquea reaprobación y ruta legacy', async () => {
    const {rows}=await db.pool.query(
        'SELECT id_pago FROM pagos WHERE id_obligacion=$1', [ids.actual]);
    const id=rows[0].id_pago;
    const aprobado=await invocar(revision.revisar,adminRevisar(id,'aprobado'));
    assert.equal(aprobado.codigo,200);
    assert.equal((await invocar(revision.revisar,adminRevisar(id,'rechazado'))).codigo,409);
    assert.equal((await invocar(directiva.actualizarEstadoPago, {
        ...admin,body:{id_pago:String(id),estado_pago:'rechazado'}
    })).codigo,409);
    const reenviar=await invocar(pagos.reportarPago,reporte(11,ids.actual));
    assert.equal(reenviar.codigo,409);
});

test('Bs reportados requieren revisión de equivalencia antes de aprobar', async () => {
    const envio=await invocar(pagos.reportarPago,reporte(11,ids.torneo,'1500.00','Bs'));
    assert.equal(envio.codigo,200);
    assert.equal(envio.body.requiere_revision_moneda,true);
    const {rows}=await db.pool.query(
        'SELECT id_pago FROM pagos WHERE id_obligacion=$1',[ids.torneo]);
    const id=rows[0].id_pago;
    assert.equal((await invocar(revision.revisar,adminRevisar(id,'aprobado'))).codigo,400);
    assert.equal((await invocar(revision.revisar,
        adminRevisar(id,'aprobado',true))).codigo,200);
    const {rows:estado}=await db.pool.query('SELECT estado_pago FROM pagos WHERE id_pago=$1',[id]);
    assert.equal(estado[0].estado_pago,'aprobado');
});

test('rechazo conserva historial y permite reenvío, sin borrar intentos', async () => {
    const {rows}=await db.pool.query(
        'SELECT id_pago FROM pagos WHERE id_obligacion=$1',[ids.siguiente]);
    const primero=rows[0].id_pago;
    assert.equal((await invocar(revision.revisar,
        adminRevisar(primero,'rechazado'))).codigo,200);
    const borrar=await invocar(directiva.eliminarPagoRechazado,{
        ...admin,params:{id_pago:String(primero)}
    });
    assert.equal(borrar.codigo,409);
    const nuevo=await invocar(pagos.reportarPago,reporte(11,ids.siguiente));
    assert.equal(nuevo.codigo,200);
    const {rows:historial}=await db.pool.query(
        'SELECT estado_pago FROM pagos WHERE id_obligacion=$1 ORDER BY id_pago',[ids.siguiente]);
    assert.deepEqual(historial.map(x=>x.estado_pago),['rechazado','pendiente']);
    const historicos=await db.pool.query(
        "SELECT id_obligacion,estado_pago FROM pagos WHERE id_atleta=11 AND mes_pagado='Octubre'");
    assert.equal(historicos.rowCount,1);
    assert.equal(historicos.rows[0].id_obligacion,null);
    assert.equal(historicos.rows[0].estado_pago,'aprobado');
});
